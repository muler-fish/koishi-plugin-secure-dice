'use strict'

exports.formatHint = (command, kind) => {
  const forms = { range: `${command} [下限,上限]`, dice: `${command} 数量d面数±修正值`, choice: `${command} 选项一 & 选项二` }
  return forms[kind] ? `格式错误。正确格式为 ${forms[kind]}` : `格式错误。正确格式为：\n${Object.values(forms).join('\n')}`
}

exports.help = ({ command = 'dice', maxDice, maxInputLength }) => `${command} 使用方法
以下“下限、上限、数量、面数、修正值、选项”都是可替换参数，不是固定内容。

1. 随机整数：${command} [下限,上限]
   两端都包含，支持负整数，下限不能大于上限。
   示例：${command} [-100,100]

2. 投骰：${command} 数量d面数±修正值
   支持 D4、D6、D8、D10、D12、D20、D100，D 不区分大小写。
   数量省略时为 1；修正值可省略；支持多组骰子加减。

3. 二选一：${command} 选项一 & 选项二 两项由你自由填写，各有 50% 概率。用一个半角 & 分隔，两项均不能为空。 示例：${command} 是 & 否

限制：区间端点在 ±1000000000 内；每次最多 ${maxDice} 颗骰子；输入最多 ${maxInputLength} 个字符。 输入 ${command} help 或仅输入 ${command} 可查看本说明。群聊调用前缀或 @ 要求沿用机器人设置。`

exports.usage = `
## Secure Dice 骰娘

生成闭区间随机整数、投掷常见面数骰子，或从用户提供的两个选项中等概率选择一个。

### 命令语法

默认主命令为 \`dice\`。**示例仅用于说明，参数均由使用者自行填写。**

| 功能 | 语法 | 参数说明 |
| --- | --- | --- |
| 使用帮助 | \`dice help\` 或 \`dice\` | 显示当前配置下的用法与限制 |
| 随机整数 | \`dice [下限,上限]\` | 两端包含，端点为整数，允许负数 |
| 投骰 | \`dice 数量d面数±修正值\` | 数量默认为 1，修正值可省略，支持多组加减 |
| 二选一 | \`dice 选项一 & 选项二\` | 自由填写两个非空选项，各 50% 概率 |

### 参数与示例

- **区间**：方括号和逗号是实际语法。例如 \`dice [-100,100]\`，可按需替换两个端点。
- **骰子**：支持 D4、D6、D8、D10、D12、D20、D100，D 不区分大小写。数量省略时为 1；修正值可省略；支持多组骰子加减。
- **选项**：中文、英文和带空格的短语均可，例如 \`dice 是 & 否\`。

### 限制与配置

| 配置项 | 默认值 | 说明 |
| --- | --- | --- |
| \`maxDice\` | 100 | 单次骰子总数上限，可设 1～100 |
| \`maxInputLength\` | 500 | 输入长度上限，可设 20～1000 |
| \`cooldownSeconds\` | 0 | 使用冷却时间（秒）。同一用户在同一会话内共用冷却，0 表示关闭。可设 0～3600。 |

区间端点与单项修正值的绝对值不超过 1000000000。暂不支持小数、乘除、括号运算、爆骰或取最高/最低。

`
